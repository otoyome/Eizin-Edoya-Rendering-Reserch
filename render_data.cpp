void render_data::set_default_sampler()
{
	ID3D11SamplerState* sampler_state[] =
	{
		sampler_states[static_cast<size_t>(render_data::SAMPLER_STATE::POINT)].Get(),
		sampler_states[static_cast<size_t>(render_data::SAMPLER_STATE::LINEAR)].Get(),
		sampler_states[static_cast<size_t>(render_data::SAMPLER_STATE::ANISOTROPIC)].Get(),
		sampler_states[static_cast<size_t>(render_data::SAMPLER_STATE::POINT_CLAMP)].Get(),
		sampler_states[static_cast<size_t>(render_data::SAMPLER_STATE::LINEAR_CLAMP)].Get(),
		sampler_states[static_cast<size_t>(render_data::SAMPLER_STATE::ANISOTROPIC_CLAMP)].Get(),
		sampler_states[static_cast<size_t>(render_data::SAMPLER_STATE::LINEAR_BORDER_BLACK)].Get(),
		sampler_states[static_cast<size_t>(render_data::SAMPLER_STATE::LINEAR_BORDER_WHITE)].Get(),
	};
	set_sampler(0, ARRAYSIZE(sampler_state), sampler_state);
}

void render_data::clear_shader_slots()
{
	immediate_context->VSSetShader(nullptr, nullptr, 0);
	immediate_context->HSSetShader(nullptr, nullptr, 0);
	immediate_context->DSSetShader(nullptr, nullptr, 0);
	immediate_context->GSSetShader(nullptr, nullptr, 0);
	immediate_context->PSSetShader(nullptr, nullptr, 0);
	immediate_context->CSSetShader(nullptr, nullptr, 0);
}

void render_data::clear_vertex_buffer()
{
	ID3D11Buffer* vbs[] = { nullptr };
	UINT dummy[] = { 0 };
	immediate_context->IASetVertexBuffers(0, 1, vbs, dummy, dummy);
}

void render_data::clear_index_buffer()
{
	immediate_context->IASetIndexBuffer(nullptr, DXGI_FORMAT_UNKNOWN, 0);
}

void render_data::clear_render_target_slots()
{
	immediate_context->OMSetRenderTargets(0, nullptr, nullptr);
}

